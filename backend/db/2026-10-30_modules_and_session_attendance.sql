-- Applebay: course modules, session-linked attendance, session start time.
-- Run once in pgAdmin (applebay database) BEFORE restarting the backend:
-- spring.jpa.hibernate.ddl-auto=validate refuses to start without these columns.
-- Safe to re-run: every statement checks whether its object already exists.

BEGIN;

-- 1. Modules group a course's contents.
CREATE TABLE IF NOT EXISTS course_modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    course_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    position INT NOT NULL DEFAULT 0,

    CONSTRAINT course_modules_course_fk
        FOREIGN KEY (course_id)
        REFERENCES courses(id)
        ON DELETE RESTRICT,

    CONSTRAINT course_modules_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0)
);

CREATE INDEX IF NOT EXISTS course_modules_course_idx
    ON course_modules (course_id, position);

-- Existing contents keep module_id NULL ("unassigned") until a lecturer moves them.
ALTER TABLE course_contents
    ADD COLUMN IF NOT EXISTS module_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'course_contents_module_fk'
    ) THEN
        ALTER TABLE course_contents
            ADD CONSTRAINT course_contents_module_fk
                FOREIGN KEY (module_id)
                REFERENCES course_modules(id)
                ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS course_contents_module_idx
    ON course_contents (module_id);

-- 2. Link each attendance mark to the session it was taken in.
-- Nullable: rows marked before sessions existed (Admin attendance page) have no session.
ALTER TABLE attendance
    ADD COLUMN IF NOT EXISTS session_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'attendance_session_fk'
    ) THEN
        ALTER TABLE attendance
            ADD CONSTRAINT attendance_session_fk
                FOREIGN KEY (session_id)
                REFERENCES attendance_sessions(id)
                ON DELETE RESTRICT;
    END IF;

    -- One mark per student per session. NULL session_id rows are not compared.
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'attendance_session_enrolment_unique'
    ) THEN
        ALTER TABLE attendance
            ADD CONSTRAINT attendance_session_enrolment_unique
                UNIQUE (session_id, enrolment_id);
    END IF;
END $$;

-- Backfill: attach existing marks to the session of the same course and date.
-- Unambiguous because attendance_sessions is UNIQUE (course_id, session_date).
UPDATE attendance a
SET session_id = s.id
FROM enrolments e, attendance_sessions s
WHERE a.session_id IS NULL
  AND e.id = a.enrolment_id
  AND s.course_id = e.course_id
  AND s.session_date = a.attendance_date;

-- 3. When the lecturer actually started the session (NULL = not started manually).
ALTER TABLE attendance_sessions
    ADD COLUMN IF NOT EXISTS started_at TIMESTAMP WITH TIME ZONE;

COMMIT;
